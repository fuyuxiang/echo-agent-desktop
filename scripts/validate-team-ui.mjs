import assert from "node:assert/strict";
import { mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { createUiReviewServer, reviewChromium } from "./ui-review-runtime.mjs";

const output = mkdtempSync(join(tmpdir(), "echo-team-ui-"));
const server = await createUiReviewServer(0, { fixture: "/scripts/fixtures/team-review.tsx" });
let browser;
let chatServer;
try {
  browser = await (await reviewChromium()).launch({ headless: true, executablePath: process.env.CHROME_BIN || "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome" });
  for (const width of [420, 1180]) for (const theme of ["light", "dark"]) {
    const page = await browser.newPage({ viewport: { width, height: 1100 } });
    const errors = []; page.on("pageerror", (error) => errors.push(error.message));
    const base = `http://127.0.0.1:${server.httpServer.address().port}/__ui-review?theme=${theme}`;
    await page.goto(base);
    await page.getByRole("button", { name: "恢复团队“123”" }).click();
    assert.equal(await page.getByRole("checkbox", { checked: true }).count(), 3);
    await page.getByRole("checkbox", { name: "文档助手", exact: true }).focus();
    await page.keyboard.press("Space");
    assert.equal(await page.getByRole("checkbox", { checked: true }).count(), 2);
    await page.keyboard.press("Space");
    assert.equal(await page.getByRole("checkbox", { checked: true }).count(), 3);
    await page.getByRole("textbox", { name: "代码专家的分工" }).fill("编写代码并运行验证");
    await page.screenshot({ path: join(output, `form-${width}-${theme}.png`) });
    await page.getByRole("button", { name: "模拟创建失败" }).click();
    await page.getByRole("button", { name: "确认创建" }).click();
    await page.getByRole("alert").filter({ hasText: "保存失败" }).waitFor();
    assert.equal(await page.getByRole("textbox", { name: "团队名称", exact: true }).inputValue(), "123");
    await page.getByRole("button", { name: "确认创建" }).click();
    await page.getByText("123", { exact: true }).waitFor();
    await page.getByText("编写代码并运行验证", { exact: true }).waitFor();
    await page.getByRole("button", { name: "使用此团队" }).click();
    assert.match(await page.getByRole("textbox", { name: "任务输入" }).inputValue(), /团队“123”/);
    await page.getByRole("button", { name: "查看任务详情" }).click();
    await page.getByRole("note").waitFor();
    await page.getByRole("button", { name: "模拟成员执行" }).click();
    await page.locator('.team-status-view__name-line [data-status="执行中"]').waitFor();
    await page.screenshot({ path: join(output, `running-${width}-${theme}.png`) });
    await page.getByRole("button", { name: "切换会话" }).click();
    await page.getByText(/本会话还没有团队/).waitFor();
    assert.equal(await page.getByText("123", { exact: true }).count(), 0);
    await page.getByRole("button", { name: "创建团队", exact: true }).click();
    await page.getByRole("checkbox", { name: "代码专家", exact: true }).check();
    await page.getByRole("textbox", { name: "团队名称", exact: true }).fill("123");
    await page.getByRole("button", { name: "确认创建" }).click();
    await page.getByText("待派发任务", { exact: true }).waitFor();
    assert.equal(await page.locator(".team-status-view__member-list > li").count(), 1);
    await page.getByRole("button", { name: "切换会话" }).click();
    await page.locator('.team-status-view__name-line [data-status="执行中"]').waitFor();
    assert.equal(await page.locator(".team-status-view__member-list > li").count(), 3);
    await page.getByRole("button", { name: "模拟读取失败" }).click();
    await page.getByRole("button", { name: "刷新", exact: true }).click();
    await page.getByRole("alert").filter({ hasText: "已保留上次结果" }).waitFor();
    assert.equal(await page.getByText("123", { exact: true }).count(), 1);
    await page.getByRole("button", { name: "刷新", exact: true }).click();
    await page.getByRole("alert").waitFor({ state: "detached" });
    const layout = await page.locator(".team-status-view").evaluate((element) => ({ width: element.clientWidth, scroll: element.scrollWidth, right: element.getBoundingClientRect().right }));
    assert.ok(layout.scroll <= layout.width + 1 && layout.right <= width, "Team panel overflows viewport");
    await page.getByRole("button", { name: "解散团队", exact: true }).click();
    await page.getByRole("button", { name: "取消解散" }).click();
    assert.equal(await page.getByText("123", { exact: true }).count(), 1);
    await page.getByRole("button", { name: "解散团队", exact: true }).click();
    await page.getByRole("button", { name: "确认解散" }).click();
    await page.getByRole("button", { name: "恢复团队“123”" }).waitFor();
    await page.reload();
    await page.getByRole("button", { name: "恢复团队“123”" }).waitFor();
    await page.getByText("本地专家定义：3 个").waitFor();
    await page.screenshot({ path: join(output, `empty-${width}-${theme}.png`) });
    assert.deepEqual(errors, []);
    await page.close();
  }
  chatServer = await createUiReviewServer(0);
  const chat = await browser.newPage({ viewport: { width: 1180, height: 900 } });
  const chatErrors = []; chat.on("pageerror", (error) => chatErrors.push(error.message));
  await chat.goto(`http://127.0.0.1:${chatServer.httpServer.address().port}/__ui-review?surface=execution&state=running&theme=light`);
  await chat.locator('[data-execution-ready="true"]').waitFor();
  await chat.getByRole("button", { name: "团队", exact: true }).click();
  await chat.getByText("review-isolated-team", { exact: true }).waitFor();
  await chat.locator(".echo-composer__input").fill("请分析我已填写的需求");
  await chat.getByRole("button", { name: "使用此团队" }).click();
  await chat.waitForFunction(() => document.querySelector(".echo-composer__input")?.value.includes("请使用团队“review-isolated-team”"));
  await chat.waitForFunction(() => document.activeElement === document.querySelector(".echo-composer__input"));
  assert.match(await chat.locator(".echo-composer__input").inputValue(), /请使用团队“review-isolated-team”/);
  assert.match(await chat.locator(".echo-composer__input").inputValue(), /^请分析我已填写的需求/);
  await chat.getByRole("button", { name: "查看任务详情" }).click();
  await chat.getByRole("region", { name: "子代理运行时" }).waitFor();
  assert.equal(await chat.getByRole("region", { name: "团队状态" }).count(), 0);
  const panelPosition = await chat.getByRole("region", { name: "子代理运行时" }).boundingBox();
  assert.ok(panelPosition && panelPosition.y >= 0 && panelPosition.y < 900, "Task navigation must reveal the subagent panel");
  await chat.screenshot({ path: join(output, "chat-integration.png") });
  assert.deepEqual(chatErrors, []);
  console.log(`Team UI passed: recovery, create/retry, member progress, draft, task details, session isolation, refresh/retry, disband/cancel, reload and production ChatView/Composer navigation; 4 layouts. Screenshots: ${output}`);
} finally { await browser?.close(); await chatServer?.close(); await server.close(); }
